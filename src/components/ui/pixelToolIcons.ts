export type ToolIconBitmapName = keyof typeof TOOL_ICON_BITMAPS;

export type ToolIconPaths = Record<ToolIconTone, string>;

const TONE_OF: Record<string, ToolIconTone | undefined> = { '#': 'ink', '+': 'shade', o: 'paint' };

/** Merge each row's runs of one tone into rectangles: `M x y h w v 1 h -w z`. */
export function compileToolIcon(rows: readonly string[]): ToolIconPaths {
  const paths: ToolIconPaths = { ink: '', shade: '', paint: '' };
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const tone = TONE_OF[row[x]];
      if (!tone) { x++; continue; }
      let end = x + 1;
      while (end < row.length && row[end] === row[x]) end++;
      paths[tone] += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  return paths;
}

const compiled = new Map<ToolIconBitmapName, ToolIconPaths>();

export function toolIconPaths(name: ToolIconBitmapName): ToolIconPaths {
  let paths = compiled.get(name);
  if (!paths) {
    paths = compileToolIcon(TOOL_ICON_BITMAPS[name]);
    compiled.set(name, paths);
  }
  return paths;
}

export function isToolIconBitmap(name: string): name is ToolIconBitmapName {
  return Object.prototype.hasOwnProperty.call(TOOL_ICON_BITMAPS, name);
}
