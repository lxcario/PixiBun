/**
 * Hand-pixeled tool icons. Every tool on the shelf is drawn on the same
 * 16 × 16 grid so the set reads as one family and stays crisp at 1:1:
 *
 *   #  ink    - the outline, in the button's text color
 *   +  shade  - the same color at low opacity, for faces and fills
 *   o  paint  - what the tool lays down or picks up (theme accent)
 *
 * Bitmaps are compiled once into one SVG path per tone, so an icon costs
 * three <path> elements however many pixels it has.
 */

export type ToolIconTone = 'ink' | 'shade' | 'paint';

