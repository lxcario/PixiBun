import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('compiled four-pixel brush agrees with detailed settings and guides stay out of exported pixels', async ({ page }, info) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/studio');
  await expect(page.locator('[data-restoration-phase="active"]')).toBeVisible();
  const artwork = page.getByTestId('main-composite-canvas');
  const pixels = () => artwork.evaluate((canvas: HTMLCanvasElement) => Array.from(canvas.getContext('2d')!.getImageData(0, 0, canvas.width, canvas.height).data));
  const original = await pixels();
  expect(original.some((value, i) => i % 4 === 3 && value !== 0)).toBe(false);
  await page.getByRole('button', { name: 'Brush size 1 pixels', exact: true }).click();
  await page.getByRole('button', { name: '4 pixel brush preset', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Brush size 4 pixels', exact: true })).toBeVisible();
  await page.getByTestId('tab-tools').click();
  await expect(page.getByRole('slider', { name: 'Tool panel brush size', exact: true })).toHaveValue('4');
  const box = (await artwork.boundingBox())!;
  const point = (x: number) => ({ x: box.x + (x + 0.5) * box.width / 32, y: box.y + 8.5 * box.height / 32 });
  await page.mouse.move(point(8).x, point(8).y);
  await page.mouse.down();
  await page.mouse.move(point(12).x, point(12).y, { steps: 4 });
  await page.mouse.up();
  await expect.poll(async () => (await pixels()).filter((value, i) => i % 4 === 3 && value !== 0).length).toBeGreaterThan(0);
  const drawn = await pixels();
  const occupied = drawn.flatMap((value, i) => i % 4 === 3 && value !== 0 ? [(i - 3) / 4] : []);
  const xs = occupied.map(i => i % 32), ys = occupied.map(i => Math.floor(i / 32));
  expect(Math.max(...ys) - Math.min(...ys) + 1).toBe(4);
  expect(occupied.length).toBe((Math.max(...xs) - Math.min(...xs) + 1) * 4);

  await page.getByRole('button', { name: 'View options menu', exact: true }).click();
  await page.getByRole('combobox', { name: /Composition/ }).selectOption('diagonals');
  await page.keyboard.press('Escape');
  await expect(page.getByTestId('diagonal-composition-guide')).toBeVisible();
  expect(await pixels()).toEqual(drawn);
  await page.getByRole('button', { name: 'View options menu', exact: true }).click();
  await page.getByRole('button', { name: /Canvas Only/i }).click();
  await expect(page.getByTestId('right-inspector')).toBeHidden();
  await expect(page.getByTestId('bottom-timeline')).toBeHidden();
  await expect(page.getByTestId('toolbar-color-dock')).toBeHidden();
  await page.getByRole('button', { name: /^Restore panels/i }).click();
  await expect(page.getByTestId('right-inspector')).toBeVisible();
  expect(await pixels()).toEqual(drawn);
  await page.getByTestId('save-button').click();
  await page.getByTestId('export-button').click();
  await page.getByTestId('export-tab-png').click();
  await page.getByRole('button', { name: '1x', exact: true }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PNG', exact: true }).click();
  const bytes = await readFile((await (await pending).path())!);
  await info.attach('four-pixel-export.png', { body: bytes, contentType: 'image/png' });
  const decoded = await page.evaluate(async base64 => {
    const image = new Image(); image.src = 'data:image/png;base64,' + base64; await image.decode();
    const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
    const ctx = canvas.getContext('2d')!; ctx.drawImage(image, 0, 0);
    return { width: image.width, height: image.height, pixels: Array.from(ctx.getImageData(0, 0, image.width, image.height).data) };
  }, bytes.toString('base64'));
  expect(decoded.width).toBe(32); expect(decoded.height).toBe(32); expect(decoded.pixels).toEqual(drawn);
  await page.keyboard.press('Escape');
  await page.getByTestId('undo-button').click();
  await expect.poll(pixels).toEqual(original);
  await page.getByTestId('redo-button').click();
  await expect.poll(pixels).toEqual(drawn);
});
